#!/usr/bin/env python3
"""Generates the Treekin string overrides in app/src/geni/res from the upstream translations.

Every <string> of app/src/main/res/values*/strings.xml that contains "Family Gem"
(except app_name, which is overridden by hand) is copied with "Family Gem" replaced by "Treekin".
Upstream files are only read. Raw XML text is copied, so escapes and placeholders stay intact.

Usage: gen_geni_strings.py          rewrite the overlay files
       gen_geni_strings.py --check  write nothing, exit 1 if the overlay is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "app/src/main/res"
OVERLAY = ROOT / "app/src/geni/res"
OLD, NEW = "Family Gem", "Treekin"
BEGIN, END = "<!-- GENERATED:BEGIN -->", "<!-- GENERATED:END -->"
STRING = re.compile(r'^\s*(<string name="([^"]+)"[^>]*>)(.*?)(</string>)\s*$')
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          '    <!-- Generated by scripts/gen_geni_strings.py from the upstream translations: do not edit by hand -->\n')


def collect(strings_file):
    """Returns the generated <string> lines of one upstream strings.xml."""
    lines = []
    for line in strings_file.read_text(encoding="utf-8").splitlines():
        m = STRING.match(line)
        if m and OLD in m.group(3) and m.group(2) != "app_name":
            text = m.group(3).replace(OLD, NEW)
            if re.search(r"family\s*gem", text, re.I):
                print(f"WARNING {strings_file.parent.name}/{m.group(2)}: still mentions Family Gem: {text}")
            lines.append(f"    {m.group(1)}{text}{m.group(4)}")
        elif OLD in line and "<string" in line and 'name="app_name"' not in line:
            print(f"WARNING {strings_file.parent.name}: unsupported multi-line string near: {line.strip()}")
    return lines


def expected():
    """Maps overlay path -> full expected content (for locales) or generated block (for values/)."""
    result = {}
    for f in sorted(UPSTREAM.glob("values*/strings.xml")):
        lines = collect(f)
        if lines:
            result[OVERLAY / f.parent.name / "strings.xml"] = lines
    return result


def render(path, lines):
    if path.parent.name == "values":
        current = path.read_text(encoding="utf-8")
        block = BEGIN + "\n" + "\n".join(lines) + "\n    " + END
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, current, flags=re.S)
    return HEADER + "\n".join(lines) + "\n</resources>\n"


def main():
    check = "--check" in sys.argv
    stale = []
    wanted = expected()
    for path, lines in wanted.items():
        content = render(path, lines)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    # Generated locale files whose source no longer mentions Family Gem
    for f in OVERLAY.glob("values-*/strings.xml"):
        if f not in wanted:
            stale.append(f)
            if not check:
                f.unlink()
    for path in stale:
        print(("STALE " if check else "wrote ") + str(path.relative_to(ROOT)))
    sys.exit(1 if check and stale else 0)


if __name__ == "__main__":
    main()
